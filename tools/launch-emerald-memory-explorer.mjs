// Developer-only launcher for the Emerald memory/state explorer (P05-T008).
// Reuses the existing per-provider local config (.env.bizhawk.local /
// .env.local) purely for already-validated executable/ROM/savestate paths;
// it does not add any new provider configuration surface. Generates a
// Lua-loadable watch list from the provider-neutral EMERALD_US_REV0
// address table (one source of truth - no hand-duplicated address list),
// then launches with adapters/{bizhawk,gen3-mgba}/memory-explorer-connector.lua
// instead of the production acquisition connector.
//
// This tool never writes to any file the production acquisition/mapping
// path reads, and never touches public/live-state.json or the production
// source snapshot path - it only produces its own diagnostic file for the
// explorer UI/server to read.
import { spawn } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { EMERALD_US_REV0 } from "../adapters/pokemon-emerald-us-rev0/emerald-us-rev0.js";
import {
  loadBizHawkProofConfig,
  validateBizHawkProofConfig,
} from "./bizhawk-proof-config.mjs";
import {
  loadEmeraldProofConfig,
  validateEmeraldProofConfig,
} from "./emerald-proof-config.mjs";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export function readArguments(args) {
  const options = { checkOnly: false, provider: null, scanStart: null, scanLength: null };
  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === "--check") {
      options.checkOnly = true;
    } else if (argument === "--provider" && args[index + 1]) {
      options.provider = args[index + 1];
      index += 1;
    } else if (argument === "--scan-start" && args[index + 1]) {
      options.scanStart = args[index + 1];
      index += 1;
    } else if (argument === "--scan-length" && args[index + 1]) {
      options.scanLength = args[index + 1];
      index += 1;
    } else {
      throw new Error(`Unknown or incomplete argument: ${argument}`);
    }
  }
  if (options.provider !== "bizhawk" && options.provider !== "mgba") {
    throw new Error("Usage: launch-emerald-memory-explorer.mjs --provider bizhawk|mgba [--check] [--scan-start 0x02000000 --scan-length 256]");
  }
  return options;
}

export function buildWatchList() {
  return Object.entries(EMERALD_US_REV0.addresses).map(([label, address]) => ({ label, address }));
}

export function watchListToLua(watches) {
  const entries = watches
    .map((watch) => `  { label = "${watch.label}", address = ${watch.address} },`)
    .join("\n");
  return `-- Generated by tools/launch-emerald-memory-explorer.mjs from\n-- adapters/pokemon-emerald-us-rev0/emerald-us-rev0.js's EMERALD_US_REV0.addresses.\n-- Not hand-maintained; regenerated on every explorer launch.\nreturn {\n${entries}\n}\n`;
}

async function launchChild(executable, args, environment) {
  const child = spawn(executable, args, {
    detached: true,
    env: environment,
    stdio: "ignore",
    windowsHide: false,
  });
  await new Promise((resolveSpawn, rejectSpawn) => {
    child.once("spawn", resolveSpawn);
    child.once("error", rejectSpawn);
  });
  child.unref();
}

async function main() {
  const options = readArguments(process.argv.slice(2));

  const watchesPath = resolve(projectRoot, "var", "snapshots", "emerald-memory-explorer.watches.lua");
  const diagnosticPath = resolve(projectRoot, "var", "snapshots", "emerald-memory-explorer.diagnostic.json");
  await mkdir(dirname(watchesPath), { recursive: true });
  const watches = buildWatchList();
  await writeFile(watchesPath, watchListToLua(watches), "utf8");
  console.log(`Wrote ${watches.length} watch(es) from EMERALD_US_REV0.addresses to ${watchesPath}`);

  const explorerEnvironment = {
    ...process.env,
    EMERALD_MEMORY_EXPLORER_WATCHES_PATH: watchesPath,
    EMERALD_MEMORY_EXPLORER_DIAGNOSTIC_PATH: diagnosticPath,
    ...(options.scanStart ? { EMERALD_MEMORY_EXPLORER_SCAN_START: String(Number(options.scanStart)) } : {}),
    ...(options.scanLength ? { EMERALD_MEMORY_EXPLORER_SCAN_LENGTH: options.scanLength } : {}),
  };

  if (options.provider === "bizhawk") {
    const config = await loadBizHawkProofConfig({ projectRoot });
    await validateBizHawkProofConfig(config);
    const connectorPath = resolve(projectRoot, "adapters", "bizhawk", "memory-explorer-connector.lua");
    await readFile(connectorPath); // fails fast if missing, matching other launchers' assertFile behavior
    const args = [
      `--lua=${connectorPath}`,
      ...(config.emeraldSavestate ? [`--load-state=${config.emeraldSavestate}`] : []),
      config.emeraldRom,
    ];
    console.log(`Diagnostic output: ${diagnosticPath}`);
    if (!options.checkOnly) {
      await launchChild(config.bizhawkExecutable, args, explorerEnvironment);
      console.log("BizHawk launched with the memory explorer diagnostic connector (not the production connector).");
    } else {
      console.log("Setup check complete; BizHawk was not launched.");
    }
  } else {
    const config = await loadEmeraldProofConfig({ projectRoot });
    await validateEmeraldProofConfig(config);
    const connectorPath = resolve(projectRoot, "adapters", "gen3-mgba", "memory-explorer-connector.lua");
    await readFile(connectorPath);
    const args = config.emeraldSavestate ? [config.emeraldRom, "--savestate", config.emeraldSavestate] : [config.emeraldRom];
    console.log(`Diagnostic output: ${diagnosticPath}`);
    if (!options.checkOnly) {
      await launchChild(config.mgbaExecutable, args, explorerEnvironment);
      console.log("mGBA launched. mGBA has no supported way to auto-load a Lua script (see P05-T006/mgba-emu/mgba#3289):");
      console.log(`Manually load the diagnostic script now: ${connectorPath}`);
    } else {
      console.log("Setup check complete; mGBA was not launched.");
    }
  }

  console.log("\nStart the explorer UI in another terminal:");
  console.log(`  EMERALD_MEMORY_EXPLORER_DIAGNOSTIC_PATH=${diagnosticPath} npm run explore:emerald`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(`Emerald memory explorer launch failed: ${error.message}`);
    process.exitCode = 1;
  });
}
